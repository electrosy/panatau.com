#!/usr/bin/env node
"use strict";

var fs = require("fs");
var path = require("path");

var ROOT = path.resolve(__dirname, "..");
var SKIP = {
  "suggest/index.html": true,
  "search.html": true
};

function walk(dir, out) {
  fs.readdirSync(dir).forEach(function (name) {
    if (name.charAt(0) === ".") return;
    var full = path.join(dir, name);
    var rel = path.relative(ROOT, full).replace(/\\/g, "/");
    var stat = fs.statSync(full);
    if (stat.isDirectory()) {
      if (name === "node_modules" || name === "images") return;
      walk(full, out);
      return;
    }
    if (name.slice(-5) === ".html") out.push(rel);
  });
}

function decode(text) {
  return String(text || "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, "\"")
    .replace(/&#39;/g, "'")
    .replace(/&ndash;/g, "–")
    .replace(/&mdash;/g, "—");
}

function stripTags(html) {
  return decode(String(html || "")
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " "))
    .replace(/\s+/g, " ")
    .replace(/\s+([.,;:])/g, "$1")
    .trim();
}

function meta(html, name) {
  var re = new RegExp("<meta[^>]+name=[\"']" + name + "[\"'][^>]*>", "i");
  var tag = html.match(re);
  if (!tag) {
    re = new RegExp("<meta[^>]+content=[\"'][^\"']*[\"'][^>]+name=[\"']" + name + "[\"'][^>]*>", "i");
    tag = html.match(re);
  }
  if (!tag) return "";
  var content = tag[0].match(/content=["']([^"']*)["']/i);
  return content ? decode(content[1]) : "";
}

function first(html, tag, cls) {
  var re = cls
    ? new RegExp("<" + tag + "[^>]*class=[\"'][^\"']*\\b" + cls + "\\b[^\"']*[\"'][^>]*>([\\s\\S]*?)</" + tag + ">", "i")
    : new RegExp("<" + tag + "[^>]*>([\\s\\S]*?)</" + tag + ">", "i");
  var m = html.match(re);
  return m ? stripTags(m[1]) : "";
}

function all(html, tag) {
  var re = new RegExp("<" + tag + "[^>]*>([\\s\\S]*?)</" + tag + ">", "gi");
  var out = [];
  var m;
  while ((m = re.exec(html))) {
    var t = stripTags(m[1]);
    if (t) out.push(t);
  }
  return out;
}

function mainBlock(html) {
  var m = html.match(/<main[\s\S]*?<\/main>/i);
  return m ? m[0] : "";
}

function excerpt(text, n) {
  var s = String(text || "").replace(/\s+/g, " ").trim();
  if (s.length <= n) return s;
  var cut = s.slice(0, n);
  var sp = cut.lastIndexOf(" ");
  if (sp > 80) cut = cut.slice(0, sp);
  return cut.replace(/[.,;:]$/, "") + "…";
}

function unique(list) {
  var seen = {};
  var out = [];
  list.forEach(function (item) {
    if (!item || seen[item]) return;
    seen[item] = true;
    out.push(item);
  });
  return out;
}

function collect() {
  var files = [];
  walk(ROOT, files);
  files.sort();
  var pages = [];
  files.forEach(function (rel) {
    if (SKIP[rel]) return;
    var html = fs.readFileSync(path.join(ROOT, rel), "utf8");
    if (/http-equiv=["']refresh["']/i.test(html) && !/<main/i.test(html)) return;
    var main = mainBlock(html);
    if (!main) return;
    var titleRaw = first(html, "title").replace(/\s+[—–-]\s+Panatau\s*$/i, "").trim();
    var h1 = first(main, "h1");
    var title = h1 || titleRaw || rel;
    var lede = first(main, "p", "lede");
    var desc = meta(html, "description");
    var description = lede.length > 36 ? lede : (desc || lede || excerpt(stripTags(main), 180));
    var keywords = unique(all(main, "h2").filter(function (h) {
      return h && h !== title;
    }));
    var text = excerpt(stripTags(main), 900);
    if (!title && !text) return;
    pages.push({
      title: title,
      url: rel,
      description: excerpt(description, 220),
      keywords: keywords,
      text: text
    });
  });
  return pages;
}

var pages = collect();
var dest = path.join(ROOT, "search-index.json");
fs.writeFileSync(dest, JSON.stringify({
  note: "Generated by scripts/build-search-index.js from the HTML pages. Rerun after adding a page.",
  pages: pages
}, null, 2) + "\n");
console.log("Wrote " + pages.length + " pages to search-index.json");
